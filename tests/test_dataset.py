"""Acceptance test of the complete data set (ADR-0009, decision 8): the anomalies of CLAUDE.md."""

import shutil
import subprocess
import sys
from datetime import date
from pathlib import Path

import pytest

from archinv.graph import build_graph, cycles
from archinv.loader import load_inventory
from archinv.report import (
    end_of_life_before,
    past_end_of_life,
    without_business_owner,
    without_it_component,
)

ROOT = Path(__file__).parent.parent
INVENTORY = ROOT / "inventory"
SCRIPT = ROOT / "scripts" / "generate_sample_inventory.py"
HEADER = "# Generated by scripts/generate_sample_inventory.py"
REFERENCE = date(2026, 10, 16)
DEADLINE = date(2028, 3, 31)


@pytest.fixture(scope="module")
def real():
    inventory = load_inventory(INVENTORY)
    return inventory, build_graph(inventory)


def test_sixty_applications(real):
    inventory, _ = real
    assert len(inventory.applications) == 60


def test_applications_without_business_owner(real):
    inventory, _ = real
    assert [a.id for a in without_business_owner(inventory)] == [
        "backup",
        "bi-reporting",
        "price-label-printing",
    ]


def test_the_only_cycle(real):
    _, graph = real
    assert cycles(graph) == [
        ("order-management", "store-inventory", "warehouse-management")
    ]


def test_components_past_end_of_life(real):
    inventory, graph = real
    assert [e.component.id for e in past_end_of_life(inventory, graph, REFERENCE)] == [
        "oracle-database-11g",
        "postgresql-12",
        "red-hat-enterprise-linux-7",
        "sql-server-2014",
        "windows-server-2012-r2",
    ]


def test_components_before_the_deadline(real):
    inventory, graph = real
    found = end_of_life_before(inventory, graph, REFERENCE, DEADLINE)
    assert [e.component.id for e in found] == ["postgresql-15", "windows-server-2016"]


def test_no_application_without_component_outside_saas(real):
    inventory, _ = real
    assert without_it_component(inventory) == []


def test_only_one_pair_with_two_link_types(real):
    inventory, _ = real
    pairs = {
        (a.id, d.application)
        for a in inventory.applications.values()
        for d in a.depends_on
        if sum(x.application == d.application for x in a.depends_on) > 1
    }
    assert pairs == {("supplier-portal", "erp-finance")}


def test_generated_files_carry_the_header_and_a_domain():
    files = sorted((INVENTORY / "applications").glob("*.yaml"))
    generated = [f for f in files if f.read_text(encoding="utf-8").startswith(HEADER)]
    assert len(generated) == 45
    for file in generated:
        assert file.read_text(encoding="utf-8").splitlines()[1].startswith("# Domain: ")


def test_committed_generated_records_match_the_script(tmp_path):
    # The local equivalent of the CI check: regenerate elsewhere and compare byte for byte.
    copy = tmp_path / "inventory"
    shutil.copytree(INVENTORY, copy)
    subprocess.run(
        [sys.executable, str(SCRIPT), str(copy)], check=True, capture_output=True
    )
    for file in sorted((copy / "applications").glob("*.yaml")):
        assert (
            file.read_bytes() == (INVENTORY / "applications" / file.name).read_bytes()
        ), file.name
