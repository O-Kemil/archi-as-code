def draw_date(rng: random.Random, start: date, end: date) -> date:
    return start + timedelta(days=rng.randint(0, (end - start).days))


def lifecycle_for(spec: Spec, rng: random.Random) -> dict[str, date]:
    active = draw_date(rng, DOMAINS[spec.domain].active_from, date(2025, 6, 30))
    lifecycle = {}
    if rng.random() < 1 / 6:
        lifecycle["plan"] = active - timedelta(days=rng.randint(300, 600))
        lifecycle["phase_in"] = active - timedelta(days=rng.randint(60, 180))
    lifecycle["active"] = active
    if spec.id in PHASE_OUT:
        lifecycle["phase_out"], lifecycle["end_of_life"] = PHASE_OUT[spec.id]
    return lifecycle


def dependencies_for(spec: Spec, earlier: list[str], rng: random.Random) -> list[dict]:
    if spec.id in NO_DEPENDENCY:
        return []
    domain = DOMAINS[spec.domain]
    count = rng.choice(domain.links)
    targets: list[str] = []
    for _ in range(count):
        pool = list(domain.pivots)
        if earlier and rng.random() > 2 / 3:
            pool = earlier
        candidates = [t for t in pool if t not in targets]
        if candidates:
            targets.append(rng.choice(candidates))
    dependencies = []
    for target in targets:
        kind = rng.choice(LINK_TYPES.get(target, GENERATED_LINK_TYPES))
        dependencies.append(
            {
                "application": target,
                "type": kind,
                "description": rng.choice(DESCRIPTIONS[kind]),
            }
        )
    return dependencies


def components_for(spec: Spec, rng: random.Random) -> list[str]:
    if spec.id in EXTRA_ANOMALIES["components"]:
        return list(EXTRA_ANOMALIES["components"][spec.id])
    if spec.hosting == "saas":
        return []
    if spec.hosting == "cloud":
        return [rng.choice(CLOUD_DB_CHOICES)]
    return [rng.choice(OS_CHOICES), rng.choice(DB_CHOICES)]


def generate() -> list[dict]:
    rng = random.Random(SEED)
    records = []
    earlier_by_domain: dict[str, list[str]] = {}
    for spec in APPLICATIONS:
        domain = DOMAINS[spec.domain]
        criticality = (
            "mission_critical"
            if spec.id in MISSION_CRITICAL
            else rng.choice(domain.criticalities)
        )
        record = {
            "id": spec.id,
            "name": spec.name,
            "description": spec.description,
            "business_owner": None
            if spec.id in EXTRA_ANOMALIES["no_business_owner"]
            else OWNER_OVERRIDES.get(spec.id, domain.business_owner),
            "technical_owner": TECHNICAL_OVERRIDES.get(spec.id, domain.technical_owner),
            "business_criticality": criticality,
            "hosting": spec.hosting,
            "lifecycle": lifecycle_for(spec, rng),
            "depends_on": dependencies_for(
                spec, earlier_by_domain.get(spec.domain, []), rng
            ),
            "it_components": components_for(spec, rng),
            "domain": spec.domain,
        }
        records.append(record)
        earlier_by_domain.setdefault(spec.domain, []).append(spec.id)
    return records


YAML_SPECIAL = set(":#'\"&*!|>%@[]{},")


def scalar(text: str) -> str:
    """Plain YAML text, or a double-quoted scalar when a character could change its meaning."""
    if any(c in YAML_SPECIAL for c in text) or text != text.strip():
        return json.dumps(text, ensure_ascii=False)
    return text


def to_yaml(record: dict) -> str:
    lines = [HEADER.rstrip("\n"), f"# Domain: {record['domain']}"]
    lines += [
        f"id: {record['id']}",
        f"name: {scalar(record['name'])}",
        f"description: {scalar(record['description'])}",
    ]
    if record["business_owner"]:
        lines.append(f"business_owner: {scalar(record['business_owner'])}")
    lines += [
        f"technical_owner: {scalar(record['technical_owner'])}",
        f"business_criticality: {record['business_criticality']}",
        f"hosting: {record['hosting']}",
        "lifecycle:",
    ]
    lines += [
        f"  {phase}: {value.isoformat()}"
        for phase, value in record["lifecycle"].items()
    ]
    if record["depends_on"]:
        lines.append("depends_on:")
        for dependency in record["depends_on"]:
            lines += [
                f"  - application: {dependency['application']}",
                f"    type: {dependency['type']}",
                f"    description: {scalar(dependency['description'])}",
            ]
    if record["it_components"]:
        lines.append("it_components:")
        lines += [f"  - {component}" for component in record["it_components"]]
    return "\n".join(lines) + "\n"


def remove_generated(directory: Path) -> int:
    removed = 0
    for file in sorted(directory.glob("*.yaml")):
        if file.read_text(encoding="utf-8").startswith(HEADER):
            file.unlink()
            removed += 1
    return removed


def main(argv: list[str] | None = None) -> int:
    arguments = sys.argv[1:] if argv is None else argv
    inventory = Path(arguments[0]) if arguments else DEFAULT_INVENTORY
    applications = inventory / "applications"
    removed = remove_generated(applications)
    records = generate()
    for record in records:
        (applications / f"{record['id']}.yaml").write_text(
            to_yaml(record), encoding="utf-8"
        )
    try:
        loaded = load_inventory(inventory)
    except InventoryError as error:
        print(error, file=sys.stderr)
        print(
            f"{len(error.errors)} error(s): the generated files are left in place",
            file=sys.stderr,
        )
        return 1
    print(
        f"Removed {removed} and wrote {len(records)} generated applications;"
        f" inventory valid: {len(loaded.applications)} applications,"
        f" {len(loaded.it_components)} IT components."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
